const dict: Record<Locale, Record<OfficeKey, string>> = { ja, en };

export function officeT(key: OfficeKey, locale: Locale, vars?: Record<string, string | number>): string {
  const raw = dict[locale][key] ?? ja[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => (vars[name] === undefined ? `{${name}}` : String(vars[name])));
}

export function useOfficeT() {
  const { locale } = useTranslation();
  const t = useCallback((key: OfficeKey, vars?: Record<string, string | number>) => officeT(key, locale, vars), [locale]);
  return { t, locale };
}

