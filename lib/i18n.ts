/**
 * UNICREW 国際化 (i18n) コア。
 *
 * - Locale = "ja" | "en"
 * - 既定は OS 言語から推測（en以外はja扱い）
 * - localStorage に永続化（unicrew.locale）
 * - useTranslation hook で React コンポーネントから利用
 * - 旧 AddonsSection の "unicrew.addons.locale" も後方互換でフォールバック
 *
 * 設計方針:
 * - 辞書は中央集権（dict.ja / dict.en の双子）。キーは namespace.key 形式。
 * - 未知キーはキー文字列をそのまま返す（落ちないように）。
 * - SSR セーフ（typeof window チェック）。
 */
"use client";

import { useEffect, useState, useCallback, useSyncExternalStore } from "react";

export type Locale = "ja" | "en";

const STORAGE_KEY = "unicrew.locale";
const LEGACY_ADDONS_KEY = "unicrew.addons.locale";

/** 値が変わったとき購読者に通知するための軽量 pub/sub。 */
const listeners = new Set<() => void>();
let currentLocale: Locale | null = null;

function detectOsLocale(): Locale {
  if (typeof navigator === "undefined") return "ja";
  const lang = (navigator.language || (navigator as { userLanguage?: string }).userLanguage || "").toLowerCase();
  if (lang.startsWith("ja")) return "ja";
  if (lang.startsWith("en")) return "en";
  // 日本以外の Latin 系は英語にフォールバック、それ以外は日本語デフォルト。
  if (/^(de|fr|es|it|pt|nl|sv|no|da|fi|pl|cs|tr|hu|ro|el|id|ms|vi)/.test(lang)) return "en";
  return "ja";
}

function readStored(): Locale | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (raw === "ja" || raw === "en") return raw;
    // 旧キー（AddonsSectionで使われていた）にフォールバック
    const legacy = window.localStorage.getItem(LEGACY_ADDONS_KEY);
    if (legacy === "ja" || legacy === "en") return legacy;
  } catch {
    /* noop */
  }
  return null;
}

/** 現在のロケール（ストア → OS推測 の順で解決）。SSRでは "ja"。 */
export function getLocale(): Locale {
  if (currentLocale) return currentLocale;
  const stored = readStored();
  currentLocale = stored ?? detectOsLocale();
  return currentLocale;
}

/** 初回起動判定: 言語選択がまだ保存されていない。 */
export function isLocaleUnset(): boolean {
  if (typeof window === "undefined") return false;
  try {
    return window.localStorage.getItem(STORAGE_KEY) === null;
  } catch {
    return false;
  }
}

/** ロケールを保存して全コンポーネントに通知。 */
export function setLocale(locale: Locale): void {
  currentLocale = locale;
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
      // 旧キーも同期しておく（AddonsSection 側の互換）
      window.localStorage.setItem(LEGACY_ADDONS_KEY, locale);
    } catch {
      /* noop */
    }
    try {
      document.documentElement.lang = locale;
    } catch {
      /* noop */
    }
  }
  listeners.forEach((cb) => {
    try { cb(); } catch { /* noop */ }
  });
}

/** React 外から購読したい場合用。 */
export function subscribeLocale(cb: () => void): () => void {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

