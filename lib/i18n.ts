const dict: Record<Locale, Dict> = { ja, en };

/** 翻訳ルックアップ。未知キーはキー自身を返す。 `{var}` プレースホルダは vars で置換。 */
export function t(
  key: string,
  varsOrLocale?: Record<string, string | number> | Locale,
  maybeLocale?: Locale,
): string {
  let vars: Record<string, string | number> | undefined;
  let locale: Locale | undefined;
  if (typeof varsOrLocale === "string") {
    locale = varsOrLocale;
  } else {
    vars = varsOrLocale;
    locale = maybeLocale;
  }
  const loc = locale ?? getLocale();
  let raw = dict[loc][key];
  if (raw === undefined) {
    // 反対言語のフォールバック（少なくとも文字列にはする）
    const other = loc === "ja" ? "en" : "ja";
    raw = dict[other][key] ?? key;
  }
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) => {
    const v = vars![name];
    return v === undefined || v === null ? `{${name}}` : String(v);
  });
}

/**
 * React hook: 現在のロケールと t() を返す。setLocale で全体が再描画される。
 */
export function useTranslation() {
  const locale = useSyncExternalStore(
    (cb) => subscribeLocale(cb),
    () => getLocale(),
    () => "ja" as Locale,
  );
  const translate = useCallback(
    (key: string, vars?: Record<string, string | number>) =>
      t(key, vars, locale),
    [locale],
  );
  return { locale, t: translate, setLocale };
}

/** クライアント側でマウント直後にロケールを反映するための helper。 */
export function useLocaleInit() {
  const [ready, setReady] = useState(false);
  useEffect(() => {
    const loc = getLocale();
    try { document.documentElement.lang = loc; } catch { /* noop */ }
    setReady(true);
  }, []);
  return ready;
}
